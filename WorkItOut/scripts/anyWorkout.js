function loadPreviousWorkoutData() { // Replace with the actual workout name
	var savedWorkoutData = JSON.parse(localStorage.getItem(workoutName.toUpperCase() +"_history"));
	
	if (savedWorkoutData) {
	  var rows = document.querySelectorAll('.new_workout_row');
	  for (var i = 0; i < savedWorkoutData.exercises.length; i++) {
		// console.log(savedWorkoutData[i]);
		var adjustedWeight = savedWorkoutData.exercises[i].weight;
		console.log(adjustedWeight);
		var weightCell = document.getElementById('workout_' +(i+1)+'_weight');
		weightCell.textContent = adjustedWeight;

		
		var adjustedSets = savedWorkoutData.exercises[i].sets;
		console.log(adjustedSets);
		var setsCell = document.getElementById('workout_' +(i+1)+'_sets');
		setsCell.textContent = adjustedSets;

		
		var adjustedReps = savedWorkoutData.exercises[i].reps;
		console.log(adjustedReps);
		var repsCell = document.getElementById('workout_' +(i+1)+'_reps');
		repsCell.textContent = adjustedReps;

		var repsCompleted = savedWorkoutData.exercises[i].repsCompleted;
		var repCells = rows[i].querySelectorAll('.new_workout_data[id^="sets_workout"]');
		for (var j = 0; j < repsCompleted.length; j++) {
		  repCells[j].textContent = repsCompleted[j];
		  repCells[j].classList.add('grayed_out');// Apply grayed-out style class
		  repCells[j].addEventListener("click", function(event){
				// Clear the text content
				event.target.textContent = "";
				// Change the class to something else (e.g., 'cleared')
				event.target.classList.add('black_text');
		  })
		}
	  }
	  if (!savedWorkoutData.notes == ""){
	  	document.querySelector("#notes_paragraph").textContent = savedWorkoutData.notes;
	  }
	}
}
  
